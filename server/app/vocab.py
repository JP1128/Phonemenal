"""Phoneme vocabulary alignment between phonemizer (espeak-ng) and wav2vec2.

The wav2vec2 phoneme tokenizer (`facebook/wav2vec2-lv-60-espeak-cv-ft`) is
trained on espeak-ng phoneme labels, but the Python `phonemizer` package's
default formatting differs in a few details: stress marks, syllable
boundaries, IPA tie bars, length marks. This module maps phonemizer output
into the model's vocabulary so the confusion matrix is meaningful.

The mapping is generated by ``scripts/verify_phoneme_vocab.py`` and stored
at ``server/app/phoneme_alias_map.json``. At runtime we apply it via
``normalize_phonemes()``.
"""
from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path
from typing import Iterable

ALIAS_PATH = Path(__file__).parent / "phoneme_alias_map.json"


# Diacritics + structural characters phonemizer emits but the model doesn't use.
_STRIP_CHARS = {
    "ˈ",  # primary stress
    "ˌ",  # secondary stress
    "ː",  # long
    ".",  # syllable boundary
    "(en)", "(en-us)",  # language-switch tags
}
_TOKEN_SEP = re.compile(r"\s+")

# Espeak-ng emits some R-colored vowels and triphthongs as a single
# concatenated symbol (e.g. "ɑɹ" for "are", "ɔɚ" for "for") that the
# wav2vec2-lv-60 vocab doesn't carry — the model has the components
# separately ("ɑ" + "ɹ"), but not the joined form. Without splitting
# these, words like "are" / "your" / "for" silently lose all phonemes
# during the vocab filter and contribute zero signal to forced
# alignment. Mapping is to component phonemes that ARE in the vocab
# (or aliased there via _load_alias_map's existing ɚ→ə rule).
_COMPOUND_SPLIT: dict[str, tuple[str, ...]] = {
    "ɑɹ": ("ɑ", "ɹ"),       # are, far, car
    "ɔɹ": ("ɔ", "ɹ"),       # or, four, more
    "aɪɹ": ("aɪ", "ɹ"),     # fire, hire (some dialects)
    "aʊɹ": ("aʊ", "ɹ"),     # hour, our (some dialects)
    "aʊə": ("aʊ", "ə"),     # tower, power
    "oʊə": ("oʊ", "ə"),     # boa, koala
    "ɪɚ": ("ɪ", "ə"),       # near, dear (ɚ aliases to ə downstream)
    "ɛɚ": ("ɛ", "ə"),       # there, hair
    "ɔɚ": ("ɔ", "ə"),       # for, north
    "ʊɚ": ("ʊ", "ə"),       # tour, sure
    "ɑɚ": ("ɑ", "ə"),       # arm, far (rhotic dialects via ɚ)
}


@lru_cache(maxsize=1)
def _load_alias_map() -> dict[str, str]:
    if not ALIAS_PATH.exists():
        return {}
    return json.loads(ALIAS_PATH.read_text())


def normalize_phonemes(raw: str | Iterable[str]) -> list[str]:
    """Turn raw phonemizer output into a sequence of model-vocab tokens.

    Accepts either a string ("h ə l oʊ") or a token iterable; returns a flat
    list ready to be looked up in the wav2vec2 tokenizer vocabulary.
    """
    if isinstance(raw, str):
        tokens = _TOKEN_SEP.split(raw.strip())
    else:
        tokens = list(raw)

    aliases = _load_alias_map()
    out: list[str] = []
    for tok in tokens:
        if not tok:
            continue
        for ch in _STRIP_CHARS:
            tok = tok.replace(ch, "")
        if not tok:
            continue
        # Split known compound symbols (R-colored vowels etc.) into
        # their component phonemes before the alias step so each piece
        # gets the chance to map cleanly into the vocab.
        if tok in _COMPOUND_SPLIT:
            for part in _COMPOUND_SPLIT[tok]:
                out.append(aliases.get(part, part))
            continue
        out.append(aliases.get(tok, tok))
    return out


def write_alias_map(mapping: dict[str, str]) -> None:
    ALIAS_PATH.write_text(json.dumps(mapping, indent=2, ensure_ascii=False))
