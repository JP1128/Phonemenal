"""Phoneme vocabulary alignment between phonemizer (espeak-ng) and wav2vec2.

The wav2vec2 phoneme tokenizer (`facebook/wav2vec2-lv-60-espeak-cv-ft`) is
trained on espeak-ng phoneme labels, but the Python `phonemizer` package's
default formatting differs in a few details: stress marks, syllable
boundaries, IPA tie bars, length marks. This module maps phonemizer output
into the model's vocabulary so the confusion matrix is meaningful.

The mapping is generated by ``scripts/verify_phoneme_vocab.py`` and stored
at ``server/app/phoneme_alias_map.json``. At runtime we apply it via
``normalize_phonemes()``.
"""
from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path
from typing import Iterable

ALIAS_PATH = Path(__file__).parent / "phoneme_alias_map.json"


# Diacritics + structural characters phonemizer emits but the model doesn't use.
_STRIP_CHARS = {
    "ˈ",  # primary stress
    "ˌ",  # secondary stress
    "ː",  # long
    ".",  # syllable boundary
    "(en)", "(en-us)",  # language-switch tags
}
_TOKEN_SEP = re.compile(r"\s+")


@lru_cache(maxsize=1)
def _load_alias_map() -> dict[str, str]:
    if not ALIAS_PATH.exists():
        return {}
    return json.loads(ALIAS_PATH.read_text())


def normalize_phonemes(raw: str | Iterable[str]) -> list[str]:
    """Turn raw phonemizer output into a sequence of model-vocab tokens.

    Accepts either a string ("h ə l oʊ") or a token iterable; returns a flat
    list ready to be looked up in the wav2vec2 tokenizer vocabulary.
    """
    if isinstance(raw, str):
        tokens = _TOKEN_SEP.split(raw.strip())
    else:
        tokens = list(raw)

    aliases = _load_alias_map()
    out: list[str] = []
    for tok in tokens:
        if not tok:
            continue
        for ch in _STRIP_CHARS:
            tok = tok.replace(ch, "")
        if not tok:
            continue
        out.append(aliases.get(tok, tok))
    return out


def write_alias_map(mapping: dict[str, str]) -> None:
    ALIAS_PATH.write_text(json.dumps(mapping, indent=2, ensure_ascii=False))
